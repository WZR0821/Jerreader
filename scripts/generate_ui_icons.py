#!/usr/bin/env python3
"""Generate both native icon renderers from our original 24-point path library."""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'design/jerreader-icons.json'
ARITY = {'M': 2, 'L': 2, 'C': 6, 'Q': 4, 'Z': 0}


def commands(value):
    tokens = re.findall(r'[MLCQZ]|-?\d+(?:\.\d+)?', value)
    index = 0
    while index < len(tokens):
        op = tokens[index]
        assert op in ARITY, (value, op)
        count = ARITY[op]
        coords = tokens[index + 1:index + count + 1]
        assert len(coords) == count
        yield op, coords
        index += count + 1


def outputs():
    icons = json.loads(SOURCE.read_text())['icons']
    kt = ['// Generated by scripts/generate_ui_icons.py; edit design/jerreader-icons.json.',
          'package com.jerreader.shared.ui', '',
          'import androidx.compose.foundation.Canvas', 'import androidx.compose.runtime.Composable',
          'import androidx.compose.ui.Modifier', 'import androidx.compose.ui.graphics.*',
          'import androidx.compose.ui.graphics.drawscope.*', '',
          'enum class JerreaderIcon { ' + ', '.join(icons) + ' }', '',
          'private data class IconPath(val path: Path, val filled: Boolean)',
          'private val iconPaths: Map<JerreaderIcon, List<IconPath>> = mapOf(']
    sw = ['// Generated by scripts/generate_ui_icons.py; edit design/jerreader-icons.json.',
          'import SwiftUI', 'import UIKit', '', 'enum JerreaderIconImage {',
          '    private static let images: [String: UIImage] = {',
          '        var result: [String: UIImage] = [:]']
    for key, icon in icons.items():
        kt.append(f'    JerreaderIcon.{key} to listOf(')
        sw += ['        do {', '            let image = UIGraphicsImageRenderer(size: CGSize(width: 24, height: 24)).image { context in',
               '                UIColor.black.setStroke(); UIColor.black.setFill()']
        for item in icon['paths']:
            fill = item.get('fill', False)
            kt.append('        IconPath(Path().apply {')
            sw += ['                do {', '                    let p = UIBezierPath()',
                   '                    p.lineWidth = 1.65; p.lineCapStyle = .round; p.lineJoinStyle = .round; p.usesEvenOddFillRule = true']
            for op, c in commands(item['d']):
                cf = [v + 'f' for v in c]
                if op == 'M':
                    kt.append(f'            moveTo({", ".join(cf)})')
                    sw.append(f'                    p.move(to: CGPoint(x: {c[0]}, y: {c[1]}))')
                elif op == 'L':
                    kt.append(f'            lineTo({", ".join(cf)})')
                    sw.append(f'                    p.addLine(to: CGPoint(x: {c[0]}, y: {c[1]}))')
                elif op == 'C':
                    kt.append(f'            cubicTo({", ".join(cf)})')
                    sw.append(f'                    p.addCurve(to: CGPoint(x: {c[4]}, y: {c[5]}), controlPoint1: CGPoint(x: {c[0]}, y: {c[1]}), controlPoint2: CGPoint(x: {c[2]}, y: {c[3]}))')
                elif op == 'Q':
                    kt.append(f'            quadraticTo({", ".join(cf)})')
                    sw.append(f'                    p.addQuadCurve(to: CGPoint(x: {c[2]}, y: {c[3]}), controlPoint: CGPoint(x: {c[0]}, y: {c[1]}))')
                else:
                    kt.append('            close()'); sw.append('                    p.close()')
            kt.append(f'            fillType = PathFillType.EvenOdd\n        }}, {str(fill).lower()}),')
            sw += ['                    p.' + ('fill()' if fill else 'stroke()'), '                }']
        kt.append('    ),')
        sw += ['            }.withRenderingMode(.alwaysTemplate)',
               '            for name in ' + json.dumps([key] + icon.get('ios', [])) + ' { result[name] = image }', '        }']
    kt += [')', '', '@Composable', 'fun JerreaderGlyph(icon: JerreaderIcon, tint: Color, modifier: Modifier = Modifier) {',
           '    Canvas(modifier) {', '        val iconScale = size.minDimension / 24f',
           '        translate((size.width - size.minDimension) / 2, (size.height - size.minDimension) / 2) {',
           '            scale(iconScale, iconScale, pivot = androidx.compose.ui.geometry.Offset.Zero) {',
           '                iconPaths.getValue(icon).forEach { part ->',
           '                    drawPath(part.path, tint, style = if (part.filled) Fill else Stroke(1.65f, cap = StrokeCap.Round, join = StrokeJoin.Round))',
           '                }', '            }', '        }', '    }', '}']
    sw += ['        return result', '    }()', '',
           '    static func image(_ name: String) -> UIImage { images[name] ?? UIImage(systemName: name) ?? UIImage() }', '}', '',
           'struct JerreaderSymbol: View {', '    let name: String', '    let size: CGFloat',
           '    nonisolated init(name: String, size: CGFloat = 20) { self.name = name; self.size = size }',
           '    var body: some View {', '        Image(uiImage: JerreaderIconImage.image(name)).resizable().scaledToFit()',
           '            .frame(width: size, height: size).accessibilityHidden(true)', '    }', '}', '',
           'struct JerreaderLabel: View {', '    let title: String', '    let icon: String',
           '    let size: CGFloat',
           '    nonisolated init(title: String, icon: String, size: CGFloat = 18) {',
           '        self.title = title; self.icon = icon; self.size = size', '    }',
           '    var body: some View {',
           '        Label { Text(LocalizedStringKey(title)) } icon: { JerreaderSymbol(name: icon, size: size) }', '    }', '}']
    return {ROOT / 'shared/src/commonMain/kotlin/com/jerreader/shared/ui/JerreaderIcons.kt': '\n'.join(kt) + '\n',
            ROOT / 'Jerreader/App/JerreaderIcons.swift': '\n'.join(sw) + '\n'}


if __name__ == '__main__':
    parser = argparse.ArgumentParser(); parser.add_argument('--check', action='store_true'); args = parser.parse_args()
    for path, value in outputs().items():
        if args.check:
            assert path.read_text() == value, f'Stale generated icons: {path.relative_to(ROOT)}'
        else:
            path.write_text(value)
    print('Both native icon renderers match the shared vector source.')
